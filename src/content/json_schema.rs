//! `red_engine2 schema`: a JSON Schema (draft 2020-12) per content format, generated from the typed definitions in `content/` and committed under
//! `schemas/` for editors and other tools (ADR 2026-10-11-one-validate-for-every-content-file). The typed definitions stay the source; a test fails
//! when `schemas/` is not what they generate.

use serde_json::{json, Value};
use std::path::{Path, PathBuf};

/// The extension namespace the checkers allow on every object (`x-*`, `x_*`, `_*`, `notes`, `$comment`), as JSON Schema `patternProperties`.
const EXTENSION_PATTERN: &str = r"^(x-|x_|_)|^notes$|^\$comment$";

